/**
 * Validates and merges the visualization object returned by Gemini with real database data.
 */
function validateAndFillVizData(vizObject, dbData) {
    if (!vizObject || typeof vizObject !== 'object') {
        return { type: 'none', title: '', data: {} };
    }

    const type = vizObject.type || 'none';
    const title = vizObject.title || '';
    let data = vizObject.data || {};

    const validTypes = ['heatmap', 'map_pins', 'bar_chart', 'line_chart', 'network_graph', 'timeline', 'geo_trail', 'none'];
    if (!validTypes.includes(type)) {
        vizObject.type = 'none';
        return vizObject;
    }

    // Merge or transform based on type
    if (dbData) {
        try {
            switch (type) {
                case 'heatmap':
                    // hotspots function returns { hotspots: [ { lat, lng, crimeCount, violentCount, recentCount, severity_score, ... } ] }
                    if (dbData.hotspots && Array.isArray(dbData.hotspots)) {
                        data.points = dbData.hotspots.map(h => ({
                            lat: parseFloat(h.lat || h.gridLat * 0.005),
                            lng: parseFloat(h.lng || h.gridLng * 0.005),
                            intensity: Math.min(10, Math.max(1, Math.round(h.severity_score || h.crimeCount))),
                            crime_type: h.top_crime_types ? h.top_crime_types[0] : 'crime'
                        }));
                    }
                    break;

                case 'map_pins':
                    // cameras-nearby returns { cameras: [ { external_id, name, type, lat, lng, coverage_radius_m, ... } ] }
                    if (dbData.cameras && Array.isArray(dbData.cameras)) {
                        data.locations = dbData.cameras.map(c => ({
                            lat: parseFloat(c.lat),
                            lng: parseFloat(c.lng),
                            label: c.name || c.external_id,
                            type: c.type || 'camera',
                            color: c.is_active ? 'green' : 'red',
                            description: `ANPR: ${c.has_anpr ? 'Yes' : 'No'}, Face Recog: ${c.has_face_recog ? 'Yes' : 'No'}`
                        }));
                    } else if (dbData.locations && Array.isArray(dbData.locations)) {
                        data.locations = dbData.locations;
                    }
                    break;

                case 'geo_trail':
                    // trail function returns { trail: [ { lat, lng, timestamp, camera_name, plate_detected, confidence, ... } ], trail_status, last_known_location }
                    if (dbData.trail && Array.isArray(dbData.trail)) {
                        data.trail = dbData.trail.map(t => ({
                            lat: parseFloat(t.lat),
                            lng: parseFloat(t.lng),
                            timestamp: t.timestamp,
                            camera_name: t.camera_name || 'Camera',
                            camera_type: t.camera_type || 'ANPR',
                            confidence: parseFloat(t.confidence || 1.0),
                            plate_detected: t.plate_detected || ''
                        }));
                        if (dbData.last_known_location) {
                            data.last_known = {
                                lat: parseFloat(dbData.last_known_location.lat),
                                lng: parseFloat(dbData.last_known_location.lng),
                                district: dbData.last_known_location.district_name || ''
                            };
                        }
                        data.trail_status = dbData.trail_status || 'tracked';
                    }
                    break;

                case 'network_graph':
                    // If DB data has nodes/edges (from network-graph-data function)
                    if (dbData.nodes && dbData.edges) {
                        data.nodes = dbData.nodes;
                        data.edges = dbData.edges;
                    }
                    break;

                case 'bar_chart':
                case 'line_chart':
                case 'timeline':
                    // Typically generated by AI directly using the context.
                    // If dbData contains structured metrics, we can map them if necessary.
                    break;
            }
        } catch (e) {
            console.error('Error transforming visualization data:', e);
        }
    }

    return { type, title, data };
}

module.exports = { validateAndFillVizData };
